"""The product's main-PCB schematic, generated from the net list (wiring/product.py).

Writes a KiCad 10 project under pcb/main/: the schematic, a symbol library for the two chips
KiCad doesn't ship (DRV5032FA, TPS629206), the library table, and a PDF of the sheet. The
schematic is label-connected (see wiring/kicad.py), so regenerating it never leaves a
dangling wire. Once PCB layout starts in KiCad, edit the schematic there or here, not both;
tests/test_wiring.py compares KiCad's own net list with wiring/product.py either way.
"""

from __future__ import annotations

import json
import subprocess
from pathlib import Path

from . import kicad as K
from .netlist import NET_TITLES, PIN_MAP, RESERVED_GPIO
from .product import FLAGGED, POWER_SYMBOLS, PRODUCT, PRODUCT_PINS, SPECS

NAME = "lochness-main"
LIB = "lochness"


def custom_symbols() -> list[list]:
    return [
        K.ic_symbol("TPS629206", "U", "3-17 V in, 600 mA buck, 4 uA Iq, SOT-583",
                    "Package_TO_SOT_SMD:SOT-583-8", "https://www.ti.com/lit/ds/symlink/tps629206.pdf",
                    left=[("6", "VIN", "power_in"), ("7", "EN", "input"), ("8", "MODE/S-CONF", "input"),
                          ("2", "PG", "open_collector")],
                    right=[("4", "SW", "power_out"), ("3", "VOS", "input"), ("1", "FB/VSET", "input"),
                           ("5", "GND", "power_in")], width=17.78),
        K.ic_symbol("DRV5032FA", "U", "Omnipolar Hall switch, push-pull, 20 Hz, SOT-23",
                    "Package_TO_SOT_SMD:SOT-23", "https://www.ti.com/lit/ds/symlink/drv5032.pdf",
                    left=[("1", "VCC", "power_in"), ("3", "GND", "power_in")],
                    right=[("2", "OUT", "output")], width=10.16),
    ]


GROUPS = [  # title, box (mm), note
    ("Battery in: reverse protection, bulk, voltage sense", (22, 35, 127, 80), ""),
    ("3.3 V buck (TPS629206)", (22, 90, 125, 160), ""),
    ("ESP32-C6-MINI-1, strapping, sleep crystal, button", (130, 35, 280, 185), ""),
    ("Programming", (285, 35, 330, 95), ""),
    ("Motor driver (DRV8833), motor + encoder connector, encoder supply switch", (335, 35, 480, 185), ""),
    ("Hall switches: bolt locked, bolt unlocked (PCB underside), door", (22, 200, 250, 260), ""),
    ("Status LED: common anode on the cells, N-FET cathode switches", (270, 190, 425, 270), ""),
]


def notes() -> list[str]:
    gp = {**{n: (g, d) for n, (g, _, d) in PIN_MAP.items()}, **PRODUCT_PINS}
    rows = sorted(gp.items(), key=lambda kv: kv[1][0])
    lines = ["GPIO map (wiring/netlist.py PIN_MAP + wiring/product.py PRODUCT_PINS):"]
    lines += [f"  GPIO{g:>2}  {n:<14} {d}" for n, (g, d) in rows]
    lines += ["  GPIO16/17 UART0 TX/RX to J3", "",
              "Open items:",
              "  - D1 has no footprint: Kingbright APTF1616 is not in KiCad's library.",
              "  - L1: check the 1008 footprint against Murata's DFE252012PD land pattern.",
              "  - J1: check the Pololu SH-style cable in a genuine JST SM06B-SRSS-TB.",
              "  - J2: check which pin the battery lead's red wire lands on.",
              "  - C1: size the bulk cap on the dev kit (motor stall on cold, aging cells).",
              "  - GPIO15 (LED_B) is a strapping pin, ignored unless the JTAG-select eFuse is burned.",
              "  - Antenna: module end over the board edge, or a copper keep-out under it."]
    return lines


def build(out: Path) -> Path:
    out.mkdir(parents=True, exist_ok=True)
    lib_path = out / f"{LIB}.kicad_sym"
    K.write_symbol_lib(lib_path, custom_symbols())
    (out / "sym-lib-table").write_text(
        f'(sym_lib_table\n\t(version 7)\n\t(lib (name "{LIB}") (type "KiCad") (uri "${{KIPRJMOD}}/{LIB}.kicad_sym") '
        '(options "") (descr "lochness parts KiCad lacks"))\n)\n')
    pro = out / f"{NAME}.kicad_pro"
    if not pro.exists():
        pro.write_text(json.dumps({"meta": {"filename": pro.name, "version": 3}}, indent=2) + "\n")

    pin_net = {pin: net for net, pins in PRODUCT.nets().items() for pin in pins}
    sheet = K.Sheet(NAME, "lochness main PCB (concept B, slab)", lib_path)
    for s in SPECS:
        fields = {"MPN": s.mpn} if s.mpn else {}
        if s.why:
            fields["Why"] = s.why
        sheet.part(K.Placed(s.ref, s.lib_id, s.value, s.footprint, s.x, s.y, s.rot, fields),
                   {pin: net for (ref, pin), net in pin_net.items() if ref == s.ref}, POWER_SYMBOLS)
    for k, net in enumerate(FLAGGED):
        sheet.flag(net, K.GRID * round((30 + 15 * k) / K.GRID), K.GRID * round(285 / K.GRID), POWER_SYMBOLS)
    sheet.text("Power flags (ERC only)", 27.94, 279.4)
    for title, (x0, y0, x1, y1), _ in GROUPS:
        sheet.box(x0, y0, x1, y1, title)
        sheet.text(title, x0 + 1.27, y0 + 1.27, 1.5, key=title)
    sheet.text("\n".join(notes()), 440, 200, 1.27, key="notes")
    sheet.text("Generated by `uv run build_wiring.py` from wiring/product.py. Every part's 'Why' field "
               "says what it is for and where its value comes from.", 22, 25, 1.5, key="hdr")
    sch = out / f"{NAME}.kicad_sch"
    sheet.write(sch, comments=["Net list: hardware/wiring/ (netlist.py, product.py)",
                               "Same circuit as the dev kit (stage 2), on the real chips"])
    subprocess.run([K.kicad_cli(), "sch", "upgrade", str(sch)], check=True, capture_output=True)
    return sch


def export_pdf(sch: Path, pdf: Path) -> None:
    subprocess.run([K.kicad_cli(), "sch", "export", "pdf", "-o", str(pdf), str(sch)], check=True, capture_output=True)


def export_svg(sch: Path, outdir: Path) -> Path:
    subprocess.run([K.kicad_cli(), "sch", "export", "svg", "-o", str(outdir), str(sch)], check=True, capture_output=True)
    return outdir / f"{sch.stem}.svg"
