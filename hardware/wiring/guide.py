def _table(head: list[str], rows: list[list[str]]) -> list[str]:
    cell = lambda s: str(s).replace("|", "\\|")
    return ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + \
        ["| " + " | ".join(cell(c) for c in r) + " |" for r in rows]


