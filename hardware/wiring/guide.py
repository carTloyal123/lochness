def _devkit_bom() -> tuple[list[dict], str]:
    rows = list(csv.DictReader(BOM_CSV.open()))
    total = next(r["Extended USD"] for r in rows if r["Category"] == "Total")
    return rows, total


def _short(part: str) -> str:
    """'Chassis tray (slab, 17 mm taller), PETG/ASA' -> 'Chassis tray'."""
    return re.sub(r", (PETG|PA12|m1 ).*$", "", re.sub(r" \(.*?\)", "", part))


